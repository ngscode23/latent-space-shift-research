# ====================== FEATURE INTERPRETATION: TOP ACTIVATING CONTEXTS ======================

def get_feature_top_contexts(
    texts,
    real_layer,
    feature_index,
    top_n=20,
    context_window=12,
    batch_size=1,
):
    """
    Показывает контексты, где SAE feature активируется сильнее всего.
    Это основной способ понять, "о чём" feature.
    """

    if real_layer not in saes:
        raise ValueError(f"SAE для layer {real_layer} не загружен")

    sae = saes[real_layer]
    hook_name = f"blocks.{real_layer}.hook_resid_post"

    records = []

    for batch_start in range(0, len(texts), batch_size):
        batch_texts = texts[batch_start:batch_start + batch_size]

        with torch.no_grad():
            tokens = model.to_tokens(batch_texts, prepend_bos=True)

            # защита от слишком длинных текстов
            if hasattr(model.cfg, "n_ctx") and tokens.shape[1] > model.cfg.n_ctx:
                tokens = tokens[:, -model.cfg.n_ctx:]

            _, cache = model.run_with_cache(
                tokens,
                names_filter=[hook_name],
            )

            act = cache[hook_name].float()          # [batch, seq, d_model]
            latent = sae.encode(act)                # [batch, seq, n_features]

            if feature_index >= latent.shape[-1]:
                raise ValueError(
                    f"feature_index={feature_index} вне диапазона. "
                    f"Всего features: {latent.shape[-1]}"
                )

            scores = latent[..., feature_index]     # [batch, seq]

            for b in range(scores.shape[0]):
                values, positions = torch.topk(
                    scores[b],
                    k=min(top_n, scores.shape[1])
                )

                str_tokens = model.to_str_tokens(tokens[b])

                for value, pos in zip(values.tolist(), positions.tolist()):
                    left = max(0, pos - context_window)
                    right = min(len(str_tokens), pos + context_window + 1)

                    context = "".join(str_tokens[left:right])
                    token = str_tokens[pos]

                    records.append({
                        "global_text_id": batch_start + b,
                        "real_layer": real_layer,
                        "feature_index": feature_index,
                        "activation": float(value),
                        "token_position": int(pos),
                        "token": token,
                        "context": context,
                    })

            del cache, act, latent, scores
            if torch.cuda.is_available():
                torch.cuda.empty_cache()

    out = pd.DataFrame(records)
    out = out.sort_values("activation", ascending=False).head(top_n)
    return out


def inspect_top_mediators_on_texts(texts, n_features=10, top_n_contexts=12):
    """
    Прогоняет top_mediators и сохраняет интерпретационные контексты.
    """

    all_rows = []

    for _, row in top_mediators.head(n_features).iterrows():
        real_layer = int(row["real_layer"])
        feature_index = int(row["feature_index"])

        print(f"\n=== layer {real_layer}, feature {feature_index} ===")

        try:
            contexts = get_feature_top_contexts(
                texts=texts,
                real_layer=real_layer,
                feature_index=feature_index,
                top_n=top_n_contexts,
                context_window=14,
                batch_size=1,
            )

            print(contexts[["activation", "token", "context"]].to_string(index=False))
            all_rows.append(contexts)

        except Exception as e:
            print(f"Ошибка: {repr(e)}")

    if len(all_rows) == 0:
        return pd.DataFrame()

    result = pd.concat(all_rows, ignore_index=True)
    result.to_csv("sae_feature_top_activating_contexts.csv", index=False)
    print("\nСохранено в sae_feature_top_activating_contexts.csv")

    return result

def patch_sae_features(activation, hook, real_layer, features_to_patch, patch_value=0.0):
    """
    Zero-ablation указанных SAE-фич в residual activation.
    Возвращает patched activation того же dtype/device.
    """
    sae = saes[real_layer]

    orig_dtype = activation.dtype
    orig_device = activation.device

    # SAE часто стабильнее кодирует в float32
    act_float = activation.to(dtype=torch.float32)

    with torch.no_grad():
        latent = sae.encode(act_float)

        for f_idx in features_to_patch:
            if 0 <= int(f_idx) < latent.shape[-1]:
                latent[..., int(f_idx)] = patch_value

        decoded = sae.decode(latent)

    return decoded.to(device=orig_device, dtype=orig_dtype)

# ====================== ОСНОВНОЙ ЭКСПЕРИМЕНТ ======================
def run_mediation_experiment(prompts_target, prompts_control=None):
    results = []

    # Проверка: есть ли вообще что патчить
    if len(top_mediators) == 0:
        raise ValueError("top_mediators пустой: не найдено order_specific/order_enriched фич.")

    if len(saes) == 0:
        raise ValueError("Не загружено ни одного SAE. Проверь release/sae_id/layers.")

    # Считаем baseline один раз на каждый слой, а не 30 раз подряд.
    # Иначе это не анализ, а платное отопление дата-центра.
    baseline_by_layer = {}

    needed_layers = sorted(set(int(x) for x in top_mediators["real_layer"].tolist() if int(x) in saes))

    for real_layer in needed_layers:
        hook_name = f"blocks.{real_layer}.hook_resid_post"

        with torch.no_grad():
            _, cache_base = model.run_with_cache(
                prompts_target,
                names_filter=[hook_name],
            )

        baseline_by_layer[real_layer] = cache_base[hook_name][:, -1, :].float().detach()

        # чистим cache объект, чтобы не держать лишнее
        del cache_base
        if torch.cuda.is_available():
            torch.cuda.empty_cache()

    for _, row in tqdm(top_mediators.iterrows(), total=len(top_mediators), desc="Causal Mediation"):
        real_layer = int(row["real_layer"])
        f_idx = int(row["feature_index"])

        if real_layer not in saes:
            continue

        hook_name = f"blocks.{real_layer}.hook_resid_post"

        resid_base = baseline_by_layer[real_layer]

        def patching_hook(act, hook):
            return patch_sae_features(
                activation=act,
                hook=hook,
                real_layer=real_layer,
                features_to_patch=[f_idx],
                patch_value=0.0,
            )

        # ВАЖНО:
        # run_with_cache(..., fwd_hooks=...) ломается в твоей версии.
        # Правильно: временно навешиваем hook через model.hooks(...),
        # а внутри уже запускаем run_with_cache.
        with torch.no_grad():
            with model.hooks(fwd_hooks=[(hook_name, patching_hook)]):
                _, cache_patched = model.run_with_cache(
                    prompts_target,
                    names_filter=[hook_name],
                )

        resid_patched = cache_patched[hook_name][:, -1, :].float().detach()

        mediated_effect = (resid_base - resid_patched).norm(dim=-1).mean().item()

        results.append({
            "real_layer": real_layer,
            "csv_layer": int(row["layer"]),
            "feature_index": f_idx,
            "x_order_orth_delta": float(row["x_order_orth_component_delta"]),
            "status": row["interpretation_status"],
            "mediated_effect": mediated_effect,
        })

        del cache_patched, resid_patched
        if torch.cuda.is_available():
            torch.cuda.empty_cache()

    if len(results) == 0:
        raise ValueError("results пустой: все real_layer отсутствуют в saes или TOP_K не дал валидных фич.")

    return pd.DataFrame(results).sort_values("mediated_effect", ascending=False)
